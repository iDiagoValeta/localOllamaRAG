export function normalizeLang(value: string | null): Lang {
  return value === 'en' || value === 'ca' || value === 'es' ? value : 'es';
}

export function fill(tpl: string, vars: Record<string, string | number>): string {
  return tpl.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** The table for one language.
 *
 * Components take this instead of ``Record<string, string>`` so a mistyped key
 * is a compile error rather than an ``undefined`` rendered into the page.
 */
